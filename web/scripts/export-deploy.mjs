// Copies SigilLaunchpad's compiled bytecode into the site for the local deploy
// page (/deploy). Run after `npx hardhat compile` in contracts/: npm run deploy:export
import { readFileSync, writeFileSync } from "node:fs";

const art = JSON.parse(readFileSync("../contracts/artifacts/contracts/SigilLaunchpad.sol/SigilLaunchpad.json", "utf8"));
const out = `// Generated by scripts/export-deploy.mjs from contracts/artifacts. Do not edit.
export const LAUNCHPAD_BYTECODE = "${art.bytecode}" as const;
export const LAUNCHPAD_CONSTRUCTOR = ${JSON.stringify(art.abi.filter((x) => x.type === "constructor"))} as const;
`;
writeFileSync("src/lib/deploy-bytecode.ts", out);
console.log(`wrote src/lib/deploy-bytecode.ts (${(art.bytecode.length - 2) / 2} bytes of bytecode)`);
